#!/usr/bin/env node
/**
 * Inline the brand drawings as one <symbol> set and point the page's placeholders
 * at it.
 *
 *   node scripts/inline-brand.mjs
 *
 * Why: an <img> or a CSS mask cannot be recoloured with currentColor, and over
 * file:// a mask-image SVG is blocked by CORS. One inline symbol set fixes both:
 * the page is self-contained, themes with the ink token, and the paths exist
 * once in the document.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const read = (p) => readFileSync(resolve(ROOT, p), 'utf8')

const SVG = {
  mk: 'brand/mark.svg',
  mkc: 'brand/mark-compact.svg',
  wm: 'brand/wordmark.svg',
  lk: 'brand/lockup.svg',
}

let symbols = ''
for (const [id, file] of Object.entries(SVG)) {
  const src = read(file)
  const viewBox = /viewBox="([^"]+)"/.exec(src)?.[1]
  if (!viewBox) throw new Error(`no viewBox in ${file}`)
  const inner = src
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\sfill="currentColor"/g, '')
  symbols += `      <symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>\n`
}

const block = `<!--BRAND-SYMBOLS: generated by scripts/inline-brand.mjs, do not edit-->
    <svg class="brand-symbols" aria-hidden="true" focusable="false">
      <defs>
${symbols}      </defs>
    </svg>
    <!--/BRAND-SYMBOLS-->`

const page = resolve(ROOT, 'design-system.html')
let html = readFileSync(page, 'utf8')

if (/<!--BRAND-SYMBOLS[\s\S]*?<!--\/BRAND-SYMBOLS-->/.test(html)) {
  html = html.replace(/<!--BRAND-SYMBOLS[\s\S]*?<!--\/BRAND-SYMBOLS-->/, block)
} else {
  html = html.replace('<body>', '<body>\n    ' + block)
}

// Placeholders → inline <svg><use>. One path, many uses.
const map = { wordmark: 'wm', mark: 'mk', 'mark-compact': 'mkc', lockup: 'lk' }
html = html.replace(
  /<span class="art art-(wordmark|mark-compact|mark|lockup)([^"]*)"([^>]*)><\/span>/g,
  (_, kind, rest, attrs) => `<svg class="art art-${kind}${rest}"${attrs}><use href="#${map[kind]}" /></svg>`,
)

writeFileSync(page, html)
console.log(JSON.stringify({ symbols: Object.keys(SVG), bytes: symbols.length, uses: (html.match(/<use href="#/g) || []).length }, null, 2))
