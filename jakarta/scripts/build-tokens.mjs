// tokens.json → CSS custom properties, a flattened JSON twin, and a contrast
// report computed from the semantic layer (never from a swatch).
//
// Three layers, always: primitive (the material) → semantic (the job) →
// component (the only place a button knows its colour). A night surface is a
// scope, not a second palette: primitives never change.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const t = JSON.parse(readFileSync(ROOT + 'src/tokens.json', 'utf8'))
const NS = t.namespace
mkdirSync(ROOT + 'tokens', { recursive: true })
mkdirSync(ROOT + 'docs', { recursive: true })

const v = (name) => `var(--${NS}-${name})`
const kebab = (s) => s.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase()

// ── colour maths ────────────────────────────────────────────────────────────
const hex2rgb = (h) => {
  const n = parseInt(h.replace('#', ''), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
const lin = (c) => {
  c /= 255
  return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4)
}
const lum = (h) => {
  const [r, g, b] = hex2rgb(h)
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
}
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}
const rgbStr = (h) => hex2rgb(h).join(', ')
const hslStr = (h) => {
  const [r, g, b] = hex2rgb(h).map((c) => c / 255)
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b)
  const l = (mx + mn) / 2
  let s = 0, hue = 0
  if (mx !== mn) {
    const d = mx - mn
    s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn)
    if (mx === r) hue = ((g - b) / d + (g < b ? 6 : 0))
    else if (mx === g) hue = (b - r) / d + 2
    else hue = (r - g) / d + 4
    hue *= 60
  }
  return `${Math.round(hue)} ${Math.round(s * 100)}% ${Math.round(l * 100)}%`
}
const oklch = (h) => {
  const [r, g, b] = hex2rgb(h).map(lin)
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  const C = Math.hypot(A, B)
  let H = (Math.atan2(B, A) * 180) / Math.PI
  if (H < 0) H += 360
  return `${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${H.toFixed(0)}`
}

// ── 1 · primitive layer ─────────────────────────────────────────────────────
const prim = Object.entries(t.color)
const primitiveCss = prim.map(([k, val]) => `  --${NS}-${k}: ${val};`).join('\n')

// ── 2 · semantic layer, resolved against the primitive map ──────────────────
const resolve = (key, mode) => {
  const target = t.semantic[mode][key]
  return t.color[target] ?? target
}

const semanticCss = (mode) =>
  Object.keys(t.semantic[mode])
    .map((k) => `  --${NS}-${kebab(k)}: ${v(t.semantic[mode][k])};`)
    .join('\n')

// ── 3 · the rest of the scales ──────────────────────────────────────────────
const typeCss = t.type
  .map(
    (s) =>
      `  --${NS}-text-${s.key}: ${s.weight} ${s.size}px/${s.lh} ${t.font.text};\n` +
      `  --${NS}-size-${s.key}: ${s.size}px;\n` +
      `  --${NS}-lh-${s.key}: ${s.lh};\n` +
      `  --${NS}-track-${s.key}: ${s.track}em;`,
  )
  .join('\n')

const spaceCss = Object.entries(t.space).map(([k, val]) => `  --${NS}-space-${k}: ${val}px;`).join('\n')
const radiusCss = Object.entries(t.radius).map(([k, val]) => `  --${NS}-radius-${k}: ${val}px;`).join('\n')
const shadowCss = Object.entries(t.shadow).map(([k, val]) => `  --${NS}-shadow-${k}: ${val};`).join('\n')
const motionCss = Object.entries(t.motion)
  .map(([k, val]) => `  --${NS}-${k === 'ease' ? 'ease' : 'dur-' + k}: ${val}${k === 'ease' ? '' : 'ms'};`)
  .join('\n')

const css = `/* ${t.name} — ${t.claim}
 * Generated by scripts/build-tokens.mjs from src/tokens.json. Do not edit.
 * Namespace --${NS}-  ·  ${prim.length} primitives  ·  ${Object.keys(t.semantic.light).length} semantic roles
 */

:root {
  /* ── 1 · primitive — the material, named once. Places, not hues. ───────── */
${primitiveCss}

  /* ── 2 · semantic — the job. Never a raw hex downstream. ──────────────── */
${semanticCss('light')}

  /* ── 3 · type ─────────────────────────────────────────────────────────── */
  --${NS}-font-display: ${t.font.display};
  --${NS}-font-text: ${t.font.text};
  --${NS}-font-code: ${t.font.code};
  /* aliases the Figma export reads — one family, three voices, no second face */
  --${NS}-font-reading: ${t.font.text};
  --${NS}-font-body: ${t.font.text};
  --${NS}-font-label: ${t.font.code};
  --${NS}-font-mono: ${t.font.code};
${typeCss}

  /* ── space · radius · shadow · motion ─────────────────────────────────── */
${spaceCss}
${radiusCss}
${shadowCss}
${motionCss}
}

/* The night scope. Primitives are untouched — only the semantic layer swaps,
 * which is what makes this a scope and not a second palette. */
html[data-${NS}='night'] {
${semanticCss('night')}
}

@media (prefers-color-scheme: dark) {
  html:not([data-${NS}]) {
${semanticCss('night')}
  }
}
`
writeFileSync(ROOT + `tokens/${t.slug}.tokens.css`, css)

// ── the JSON twin: same values, resolved, for tools that cannot read var() ──
const flat = {
  name: t.name, slug: t.slug, namespace: NS, version: t.version,
  primitive: t.color,
  semantic: {
    light: Object.fromEntries(Object.keys(t.semantic.light).map((k) => [kebab(k), resolve(k, 'light')])),
    night: Object.fromEntries(Object.keys(t.semantic.night).map((k) => [kebab(k), resolve(k, 'night')])),
  },
  type: Object.fromEntries(t.type.map((s) => [s.key, s])),
  space: t.space, radius: t.radius, shadow: t.shadow, motion: t.motion,
  ramps: t.ramps, mark: t.mark,
}
writeFileSync(ROOT + `tokens/${t.slug}.tokens.json`, JSON.stringify(flat, null, 2))

// ── contrast, computed from the semantic layer, both scopes ────────────────
const PAIRS = [
  ['text', 'surface', 4.5, 'body text'],
  ['text', 'surface-raised', 4.5, 'body text on a card'],
  ['text-muted', 'surface', 4.5, 'secondary text'],
  ['text-faint', 'surface', 3, 'tertiary / large only'],
  ['accent', 'surface', 4.5, 'accent as text'],
  ['accent-ink', 'accent', 4.5, 'button label'],
  ['text-inverse', 'surface-inverse', 4.5, 'inverse band'],
  ['rule-strong', 'surface', 3, 'hairline that carries meaning'],
  ['transit', 'surface', 4.5, 'transit label'],
  ['park', 'surface', 4.5, 'park label'],
  ['heritage', 'surface', 4.5, 'heritage label'],
  ['digital', 'surface', 4.5, 'digital label'],
  ['night', 'surface', 4.5, 'night label'],
  ['alert', 'surface', 4.5, 'alert label'],
]

const report = { generated: new Date().toISOString(), scopes: {} }
for (const mode of ['light', 'night']) {
  report.scopes[mode] = PAIRS.map(([fg, bg, min, job]) => {
    const a = resolve(fg, mode), b = resolve(bg, mode)
    const r = ratio(a, b)
    return { fg, bg, a, b, job, min, ratio: +r.toFixed(2), pass: r >= min }
  })
}
// the ramps themselves, against the two grounds they will actually sit on
report.ramps = t.ramps.map((r) => {
  const hex = t.color[`${r.key}-100`]
  const onPaper = ratio(hex, t.color.kertas)
  const onWhite = ratio(hex, t.color.kapur)
  return {
    key: r.key, name: r.name, hex, onPaper: +onPaper.toFixed(2), onWhite: +onWhite.toFixed(2),
    bodyOnPaper: onPaper >= 4.5, largeOnPaper: onPaper >= 3,
  }
})
writeFileSync(ROOT + 'docs/contrast.json', JSON.stringify(report, null, 2))

// ── swatch data for the page ───────────────────────────────────────────────
const swatches = prim.map(([k, val]) => ({
  key: k, hex: val, rgb: rgbStr(val), hsl: hslStr(val), oklch: oklch(val),
  varName: `--${NS}-${k}`,
}))
writeFileSync(ROOT + 'src/swatches.json', JSON.stringify(swatches, null, 0))

const fails = [...report.scopes.light, ...report.scopes.night].filter((p) => !p.pass)
console.log(`tokens: ${prim.length} primitives, ${Object.keys(t.semantic.light).length} roles`)
console.log(`contrast: ${report.scopes.light.filter((p) => p.pass).length}/${PAIRS.length} light pass, ` +
  `${report.scopes.night.filter((p) => p.pass).length}/${PAIRS.length} night pass`)
for (const f of fails) console.log(`  fail ${f.fg} on ${f.bg} = ${f.ratio}:1 (needs ${f.min})`)
for (const r of report.ramps) console.log(`  ramp ${r.key.padEnd(10)} ${r.hex}  ${r.onPaper}:1 paper  ${r.onWhite}:1 white`)
